let leadsStore: Lead[] = [...INITIAL_LEADS];

export const LeadService = {
  async list(): Promise<Lead[]> {
    await new Promise((r) => setTimeout(r, 60));
    return [...leadsStore];
  },

  async updateStage(id: string, stage: LeadStage): Promise<Lead | null> {
    await new Promise((r) => setTimeout(r, 40));
    const index = leadsStore.findIndex((l) => l.id === id);
    if (index === -1) return null;
    leadsStore[index] = {
      ...leadsStore[index],
      stage,
      lastContactAt: new Date().toISOString(),
    };
    return leadsStore[index];
  },

  async reorderLeads(newLeads: Lead[]): Promise<void> {
    leadsStore = [...newLeads];
  },

  async addLead(lead: Omit<Lead, "id" | "createdAt" | "lastContactAt">): Promise<Lead> {
    await new Promise((r) => setTimeout(r, 100));
    const newLead: Lead = {
      ...lead,
      id: `lead-${Date.now()}`,
      dealValue: lead.dealValue || lead.budgetMax || 250000,
      createdAt: new Date().toISOString(),
      lastContactAt: new Date().toISOString(),
      statusBadge: lead.statusBadge || "Nova",
      rating: lead.rating || 1,
    };
    leadsStore.unshift(newLead);
    return newLead;
  }
};
